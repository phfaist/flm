//! The emitter of `flm-ext/flm.d.ts`, the TypeScript declarations of every
//! module of the extension API (the plan's section 5.3, `dev-docs/ext/e2b`).
//!
//! One `declare module` per module in the order of their paths, opening with
//! the imports of the types it uses from other modules and its re-exports
//! (the submodules of the surface as namespaces last). A
//! façade trait or an opaque type is a class (`private constructor()` where
//! Rust has no constructor, `protected` when a hand-written class extends
//! it); an extension-side trait an interface, a method with a default body
//! optional; a unit enum a `Readonly` object of its
//! tokens and the union of them under the same name; a data enum the frozen
//! object of its static constructors and the union of the mapping table's
//! row; a data struct with a class in the stub a class; a data type with a
//! row an interface or a type; a constant its literal type; a hand-written
//! export the hand list's text. Each item carries the first sentence of its
//! rustdoc as JSDoc, intra-doc links reduced to their text.
//!
//! A type the mapping table writes as an interface (`interface NodeAddr
//! {…}`) that no module of the inventory defines is declared in the first
//! module that uses it.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use serde_json::Value;

use crate::inventory::{FirstStatement, Function, Inventory, Item, ItemClass, ItemKind, Module};
use crate::js_out::{defined_elsewhere, plain};
use crate::mapping::{self, Shape, Ts, TypeRow};

/// The generated declarations, from the crate's root.
pub const FLM_D_TS: &str = "flm.d.ts";

/// The declarations of one module, before the imports are known.
struct Block {
    /// The module's path.
    path: String,
    /// The re-export lines.
    reexports: Vec<String>,
    /// The declarations, each a text indented by two spaces.
    body: Vec<String>,
}

/// The emitter's state: the inventory and the names each module declares.
struct Emitter<'a> {
    /// The inventory.
    inventory: &'a Inventory,
    /// The module that declares each type name.
    declared: BTreeMap<String, String>,
}

/// `flm.d.ts`, the values of the constants read from the compiled table
/// (`(module, name, value)`).
pub fn emit(inventory: &Inventory, constants: &[(String, String, Value)]) -> String {
    let mut emitter = Emitter { inventory, declared: BTreeMap::new() };
    let mut blocks: Vec<Block> = inventory.modules.iter().map(|module| emitter.block(module, constants)).collect();
    // The interfaces of the table that no module defines, in the first
    // module that uses them.
    for row in mapping::TYPES {
        let Ts::Text(text) = row.ts else { continue };
        if !declaration(text) || emitter.declared.contains_key(row.rust) {
            continue;
        }
        if let Some(block) = blocks.iter_mut().find(|block| block.body.iter().any(|text| uses(text).contains(row.rust))) {
            block.body.push(format!("  export {}\n", terminated(text)));
            emitter.declared.insert(row.rust.to_string(), block.path.clone());
        }
    }
    let mut out = format!(
        "// Generated by `tests/api_surface.rs` of flm-ext {} from the sources under\n// `flm-ext/src/api/`; do not edit.\n",
        env!("CARGO_PKG_VERSION")
    );
    for block in &blocks {
        let _ = write!(out, "\ndeclare module \"flm:{}\" {{\n", block.path);
        let mut imports: BTreeMap<&str, BTreeSet<String>> = BTreeMap::new();
        for text in &block.body {
            for name in uses(text) {
                if let Some(home) = emitter.declared.get(&name)
                    && *home != block.path
                {
                    imports.entry(home.as_str()).or_default().insert(name);
                }
            }
        }
        for (home, names) in &imports {
            let _ = writeln!(out, "  import {{ {} }} from \"flm:{home}\";", names.iter().cloned().collect::<Vec<_>>().join(", "));
        }
        for line in &block.reexports {
            let _ = writeln!(out, "  {line}");
        }
        for text in &block.body {
            out.push('\n');
            out.push_str(text);
        }
        out.push_str("}\n");
    }
    out
}

/// Whether the table's text `text` is a declaration of its own (`interface
/// X {…}`, `type X = …`, `class X {…}`) rather than a type written in place.
fn declaration(text: &str) -> bool {
    text.starts_with("interface ") || text.starts_with("type ") || text.starts_with("class ")
}

/// The table's declaration `text` as a statement: a type alias ends in `;`.
fn terminated(text: &str) -> String {
    if text.starts_with("type ") && !text.ends_with(';') { format!("{text};") } else { text.to_string() }
}

/// The identifiers a declaration's text uses outside its comments and its
/// string literals.
fn uses(text: &str) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    for line in text.lines() {
        let line = line.trim_start();
        if line.starts_with("/**") || line.starts_with('*') || line.starts_with("//") {
            continue;
        }
        let mut word = String::new();
        let mut quoted = false;
        for c in line.chars().chain(std::iter::once(' ')) {
            if c == '"' {
                quoted = !quoted;
                word.clear();
                continue;
            }
            if quoted {
                continue;
            }
            if c.is_alphanumeric() || c == '_' {
                word.push(c);
            } else if !word.is_empty() {
                out.insert(std::mem::take(&mut word));
            }
        }
    }
    out
}

/// `text` with every line indented by `indent`.
fn indented(text: &str, indent: &str) -> String {
    text.lines().map(|line| if line.is_empty() { "\n".to_string() } else { format!("{indent}{line}\n") }).collect()
}

/// The JSDoc line of `doc` at `indent`; nothing for an empty text.
fn jsdoc(doc: &str, indent: &str) -> String {
    if doc.is_empty() { String::new() } else { format!("{indent}/** {} */\n", plain(doc).replace("*/", "*\\/")) }
}

/// The TypeScript literal type of the constant's value; `top` for the
/// outermost list, which is `readonly`.
fn literal_type(value: &Value, top: bool) -> String {
    match value {
        Value::Array(items) => {
            let items: Vec<String> = items.iter().map(|item| literal_type(item, false)).collect();
            format!("{}[{}]", if top { "readonly " } else { "" }, items.join(", "))
        }
        other => other.to_string(),
    }
}

/// `t[]`, parenthesized when `t` is a union.
fn array(t: &str) -> String {
    if t.contains(" | ") { format!("({t})[]") } else { format!("{t}[]") }
}

impl Emitter<'_> {
    /// The TypeScript type of the normalized Rust type `ty` (the plan's
    /// sections 4.2 and 4.3).
    ///
    /// # Panics
    ///
    /// On a type the table and the structural rules cannot write; the
    /// table test names it first.
    fn ts(&self, ty: &str) -> String {
        if let Some(row) = mapping::row(ty) {
            return self.row_ts(row);
        }
        match mapping::shape(ty) {
            Shape::Ref { inner, .. } => self.ts(&inner),
            Shape::Slice(inner) => array(&self.ts(&inner)),
            Shape::Tuple(elems) if elems.is_empty() => "void".to_string(),
            Shape::Tuple(elems) => format!("[{}]", elems.iter().map(|elem| self.ts(elem)).collect::<Vec<_>>().join(", ")),
            Shape::Generic { head, args } => match (head.as_str(), args.as_slice()) {
                ("Result", [ok, _]) => self.ts(ok),
                ("Option", [inner]) => format!("{} | null", self.ts(inner)),
                ("Vec", [inner]) => array(&self.ts(inner)),
                ("Box" | "Arc", [inner]) => self.ts(inner),
                _ => panic!("the type `{ty}` must have a row in `tests/api_surface/mapping.rs`"),
            },
            Shape::Dyn(bounds) => bounds.first().cloned().unwrap_or_default(),
            Shape::Impl(bounds) => match mapping::shape(bounds.first().map_or("", String::as_str)) {
                Shape::Generic { head, args } if head == "Into" && args.len() == 1 => self.ts(&args[0]),
                Shape::Generic { head, args } if head == "IntoIterator" && args.len() == 1 => {
                    array(&self.ts(args[0].strip_prefix("Item = ").unwrap_or(&args[0])))
                }
                _ => panic!("the type `{ty}` must have a row in `tests/api_surface/mapping.rs`"),
            },
            Shape::Plain(name) if mapping::kind_of(&name).is_some() => name,
            Shape::Plain(_) => panic!("the type `{ty}` must have a row in `tests/api_surface/mapping.rs`"),
        }
    }

    /// The TypeScript type a row writes in place.
    fn row_ts(&self, row: &TypeRow) -> String {
        match row.ts {
            Ts::Text(text) if declaration(text) || self.inventory.definition(row.rust).is_some() => row.rust.to_string(),
            Ts::Text(text) => text.to_string(),
            Ts::Union | Ts::Class | Ts::Hand => row.rust.to_string(),
            Ts::Handle => row.rust.trim_start_matches("Box<dyn ").trim_end_matches('>').to_string(),
            Ts::NotOffered => panic!("the type `{}` is not offered to a script and cannot be written in `flm.d.ts`", row.rust),
        }
    }

    /// A method's or a function's signature: `name(p: T): R`.
    fn signature(&self, function: &Function, output: &str) -> String {
        let params: Vec<String> = function.params.iter().map(|param| format!("{}: {}", param.name, self.ts(&param.ty))).collect();
        format!("{}({}): {output}", function.name, params.join(", "))
    }

    /// The declarations of one module.
    fn block(&mut self, module: &Module, constants: &[(String, String, Value)]) -> Block {
        let mut block = Block { path: module.path.clone(), reexports: Vec::new(), body: Vec::new() };
        for item in &module.items {
            if let Some(home) = defined_elsewhere(self.inventory, &module.path, item) {
                if mapping::row(&item.name).is_none_or(|row| row.ts != Ts::NotOffered) {
                    block.reexports.push(format!("export {{ {} }} from \"flm:{home}\";", item.name));
                }
                continue;
            }
            let text = self.item(module, item, constants);
            if !text.is_empty() {
                if !matches!(item.class, ItemClass::Constant | ItemClass::Function) {
                    self.declared.insert(item.name.clone(), module.path.clone());
                }
                block.body.push(text);
            }
        }
        for name in self.inventory.submodules(&module.path) {
            block.reexports.push(format!("export * as {name} from \"flm:{}/{name}\";", module.path));
        }
        block
    }

    /// The declaration of one item (empty when it has none).
    fn item(&self, module: &Module, item: &Item, constants: &[(String, String, Value)]) -> String {
        if let Some(hand) = mapping::HAND_WRITTEN.iter().find(|hand| hand.module == module.path && hand.item == item.name) {
            return format!("{}{}", jsdoc(&item.doc, "  "), indented(hand.ts, "  "));
        }
        let doc = jsdoc(&item.doc, "  ");
        match (&item.class, &item.kind) {
            (ItemClass::SealedTrait | ItemClass::OpaqueType, _) => format!("{doc}{}", self.class(module, item)),
            (ItemClass::ExtensionTrait, ItemKind::Trait { methods, .. }) => {
                let mut out = format!("{doc}  export interface {} {{\n", item.name);
                for method in methods {
                    out.push_str(&jsdoc(&method.doc, "    "));
                    let optional = if method.default_body || mapping::is_optional_in_scripts(&item.name, &method.name) { "?" } else { "" };
                    let signature = self.signature(method, &self.ts(&method.output));
                    let (name, rest) = signature.split_at(method.name.len());
                    let _ = writeln!(out, "    {name}{optional}{rest};");
                }
                out.push_str("  }\n");
                out
            }
            (ItemClass::DataClass, _) => format!("{doc}{}", self.data_class(module, item)),
            (ItemClass::DataType | ItemClass::CoreReexport, _) => {
                let Some(row) = mapping::row(&item.name) else { return String::new() };
                let mut out = String::new();
                if let Some(object) = mapping::STATIC_OBJECTS.iter().find(|object| object.rust == item.name) {
                    let members: Vec<&str> = object.members.iter().map(|member| member.ts).collect();
                    let _ = writeln!(out, "  export const {}: Readonly<{{ {} }}>;", item.name, members.join("; "));
                }
                match row.ts {
                    Ts::Union => {
                        let tokens = mapping::unit_enum_tokens(&item.name).expect("the table test checks the tokens of every unit enum");
                        let members: Vec<String> = tokens.iter().map(|(variant, token)| format!("{variant}: {token}")).collect();
                        let union: Vec<String> = tokens.iter().map(|(_, token)| token.to_string()).collect();
                        let _ = writeln!(out, "  export const {}: Readonly<{{ {} }}>;", item.name, members.join("; "));
                        let _ = writeln!(out, "  export type {} = {};", item.name, union.join(" | "));
                    }
                    Ts::Text(text) if declaration(text) => {
                        let _ = writeln!(out, "  export {}", terminated(text));
                    }
                    Ts::Text(text) => {
                        let _ = writeln!(out, "  export type {} = {};", item.name, text);
                    }
                    _ => {}
                }
                if out.is_empty() { out } else { format!("{doc}{out}") }
            }
            (ItemClass::Constant, _) => {
                let value = constants
                    .iter()
                    .find(|(path, name, _)| *path == module.path && *name == item.name)
                    .map(|(_, _, value)| value)
                    .expect("the values of the constants were checked against the inventory");
                format!("{doc}  export const {}: {};\n", item.name, literal_type(value, true))
            }
            (ItemClass::Function, ItemKind::Function(function)) => {
                let ts = match mapping::EXTRA_METHODS.iter().find(|extra| extra.owner == module.path && extra.name == function.name) {
                    Some(extra) => extra.ts.to_string(),
                    None => self.signature(function, &self.ts(&function.output)),
                };
                format!("{doc}  export function {ts};\n")
            }
            _ => String::new(),
        }
    }

    /// The class of a façade trait or an opaque type.
    fn class(&self, module: &Module, item: &Item) -> String {
        let kind = mapping::kind_of(&item.name).expect("the table test checks the kind of every handle");
        let methods: &[Function] = match &item.kind {
            ItemKind::Trait { methods, .. } | ItemKind::Type { methods, .. } => methods,
            _ => &[],
        };
        let mut body = String::new();
        let constructor = methods.iter().find(|method| method.is_constructor() && !mapping::is_excluded(&item.name, &method.name));
        match constructor {
            Some(new) => body.push_str(&self.method_text(module, item, new, "constructor")),
            None if mapping::is_extended_by_hand(&item.name) => body.push_str("    protected constructor();\n"),
            None => body.push_str("    private constructor();\n"),
        }
        for method in methods.iter().filter(|method| !method.is_constructor() && !mapping::is_excluded(&item.name, &method.name)) {
            match mapping::EXTRA_METHODS.iter().find(|extra| extra.owner == kind.kind && extra.name == method.name) {
                Some(extra) => {
                    body.push_str(&jsdoc(&method.doc, "    "));
                    let _ = writeln!(body, "    {};", extra.ts);
                }
                None => body.push_str(&self.method_text(module, item, method, &method.name)),
            }
        }
        for extra in mapping::EXTRA_METHODS.iter().filter(|extra| extra.owner == kind.kind) {
            if !methods.iter().any(|method| method.name == extra.name) {
                let _ = writeln!(body, "    {};", extra.ts);
            }
        }
        format!("  export class {} {{\n{body}  }}\n", item.name)
    }

    /// One method of a class, `name` its name in the class (`constructor`
    /// for `new`): the hand list's text, or the signature.
    fn method_text(&self, module: &Module, item: &Item, method: &Function, name: &str) -> String {
        let doc = jsdoc(&method.doc, "    ");
        let key = format!("{}.{name}", item.name);
        if let Some(hand) = mapping::HAND_WRITTEN.iter().find(|hand| hand.module == module.path && hand.item == key) {
            return format!("{doc}{}", indented(hand.ts, "    "));
        }
        let params: Vec<String> = method.params.iter().map(|param| format!("{}: {}", param.name, self.ts(&param.ty))).collect();
        if name == "constructor" {
            format!("{doc}    constructor({});\n", params.join(", "))
        } else {
            format!("{doc}    {name}({}): {};\n", params.join(", "), self.ts(&method.output))
        }
    }

    /// The class of a data struct.
    fn data_class(&self, module: &Module, item: &Item) -> String {
        let ItemKind::Type { fields, methods, .. } = &item.kind else { return String::new() };
        let mut body = String::new();
        for method in methods {
            if method.is_constructor() {
                body.push_str(&self.method_text(module, item, method, "constructor"));
                continue;
            }
            let key = format!("{}.{}", item.name, method.name);
            if let Some(hand) = mapping::HAND_WRITTEN.iter().find(|hand| hand.module == module.path && hand.item == key) {
                body.push_str(&jsdoc(&method.doc, "    "));
                body.push_str(&indented(hand.ts, "    "));
                continue;
            }
            let output = match method.first {
                Some(FirstStatement::Get(_)) => self.ts(&method.output),
                _ => "this".to_string(),
            };
            body.push_str(&jsdoc(&method.doc, "    "));
            body.push_str(&format!("    {};\n", self.signature(method, &output)));
        }
        let fields: Vec<String> = fields.iter().map(|field| format!("{}: {}", field.name, self.ts(&field.ty))).collect();
        let _ = writeln!(body, "    toJSON(): {{ {} }};", fields.join("; "));
        format!("  export class {} {{\n{body}  }}\n", item.name)
    }
}
