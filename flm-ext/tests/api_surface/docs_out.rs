//! The emitter of `src/quickjs/api_modules.md`, the table of the API modules
//! that the module page of `flm_ext::quickjs` includes under its heading
//! "The API modules" (the plan's section 5.4, `dev-docs/ext/e2b`): one row per
//! module, with the `api` module it mirrors as an intra-doc link and its
//! exports in the stub's order.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::inventory::Inventory;

/// The generated table, from the crate's root.
pub const API_MODULES_MD: &str = "src/quickjs/api_modules.md";

/// The table, `exports` the exports of each module by its path.
pub fn emit(inventory: &Inventory, exports: &BTreeMap<String, Vec<String>>) -> String {
    let mut out = String::from(
        "<!-- Generated by `tests/api_surface.rs` from the sources under `flm-ext/src/api/`; do not edit. -->\n\
         \n\
         | Module | Mirrors | Exports |\n\
         |---|---|---|\n",
    );
    for module in &inventory.modules {
        let rust = module.path.replace('/', "::");
        let names: Vec<String> = exports.get(&module.path).map_or_else(Vec::new, |names| names.iter().map(|name| format!("`{name}`")).collect());
        let _ = writeln!(out, "| `flm:{}` | [`api::{rust}`](crate::api::{rust}) | {} |", module.path, names.join(", "));
    }
    out
}
