// The build of flm-lecturenotes, the member `lecturenotes` of the workspace npm/.
//
//   node build.mjs              type check, then write lecturenotes.js and
//                               lecturenotes.css into the folder `dist/` of the
//                               extension's compose template (DIST)
//   node build.mjs --out DIR    the same, written into DIR instead of DIST
//   node build.mjs test         compile test/*.ts into target/test/ and run them
//                               with node's test runner
//
// The script is bundled by esbuild from src/index.ts as one IIFE assigning the
// global name `flmLecturenotes`, not minified; its source map stays in
// target/staging/, beside the script as built there, and the script holds no
// link to it. The stylesheet is the files of src/style/ joined in the order of
// STYLE_FILES, with no processing. Each output begins with the line GENERATED.
// Neither output may hold the delimiters of the FLM template that includes them.
// The type checker and esbuild are the workspace's (`npm install` in npm/).
// esbuild works from this script's folder, so the outputs are the same from
// whichever folder the script is run.

import { execFileSync, spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));

/** The folder of the bundle the extension ships: `dist/` in its compose template's folder. */
const DIST = join(here, '..', '..', 'extensions', 'data', 'lecturenotes', 'templates', 'html', 'lecturenotes', 'dist');

/** The first line of each output, without the comment's delimiters. */
const GENERATED = 'Generated by npm/lecturenotes (node build.mjs); do not edit.';

/** The stylesheet's files, in the order they are joined. */
const STYLE_FILES = [
  'base.css',
  'frame.css',
  'toc.css',
  'content.css',
  'math.css',
  'previews.css',
  'print.css',
];

/**
 * The delimiters of the FLM template that includes the bundle (its description's
 * `delimiters`: the usual ones of the minijinja engine). The bundle is included
 * as it is, but a delimiter in it would break the day a template processes it.
 */
const DELIMITERS = ['{%', '%}', '{{', '}}', '{#', '#}'];

/** The browsers the script is written for: the current evergreen ones. */
const TARGET = ['es2022'];

function typeCheck() {
  const tsc = join(here, '..', 'node_modules', '.bin', 'tsc');
  execFileSync(tsc, ['--noEmit', '-p', join(here, 'tsconfig.json')], { stdio: 'inherit' });
}

async function buildScript(outDir) {
  await esbuild.build({
    absWorkingDir: here,
    entryPoints: [join(here, 'src', 'index.ts')],
    outfile: join(outDir, 'lecturenotes.js'),
    bundle: true,
    format: 'iife',
    globalName: 'flmLecturenotes',
    target: TARGET,
    minify: false,
    sourcemap: 'external',
    banner: { js: `// ${GENERATED}` },
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'warning',
  });
}

function buildStyle(outDir) {
  const parts = STYLE_FILES.map((name) => readFileSync(join(here, 'src', 'style', name), 'utf8').trimEnd() + '\n');
  writeFileSync(join(outDir, 'lecturenotes.css'), `/* ${GENERATED} */\n` + parts.join('\n'));
}

/** Fails when an output holds one of the template's delimiters. */
function checkDelimiters(outDir) {
  const problems = [];
  for (const name of ['lecturenotes.js', 'lecturenotes.css']) {
    const lines = readFileSync(join(outDir, name), 'utf8').split('\n');
    lines.forEach((line, i) => {
      for (const delimiter of DELIMITERS) {
        if (line.includes(delimiter)) {
          problems.push(`${name}, line ${i + 1}: \`${delimiter}\` must not appear in the bundle, since the template that includes it uses it as a delimiter`);
        }
      }
    });
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem);
    process.exit(1);
  }
}

/**
 * Builds into target/staging/, checks, then copies the two outputs into `outDir`;
 * the source map stays in target/staging/.
 */
async function build(outDir) {
  typeCheck();
  const staging = join(here, 'target', 'staging');
  rmSync(staging, { recursive: true, force: true });
  mkdirSync(staging, { recursive: true });
  await buildScript(staging);
  buildStyle(staging);
  checkDelimiters(staging);
  mkdirSync(outDir, { recursive: true });
  for (const name of ['lecturenotes.js', 'lecturenotes.css']) {
    copyFileSync(join(staging, name), join(outDir, name));
  }
}

async function test() {
  const outDir = join(here, 'target', 'test');
  rmSync(outDir, { recursive: true, force: true });
  const files = readdirSync(join(here, 'test')).filter((name) => name.endsWith('.test.ts')).sort();
  await esbuild.build({
    absWorkingDir: here,
    entryPoints: files.map((name) => join(here, 'test', name)),
    outdir: outDir,
    outExtension: { '.js': '.mjs' },
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: ['node:*'],
    logLevel: 'warning',
  });
  const compiled = files.map((name) => join(outDir, name.replace(/\.ts$/, '.mjs')));
  const run = spawnSync(process.execPath, ['--test', ...compiled], { stdio: 'inherit' });
  process.exit(run.status ?? 1);
}

const args = process.argv.slice(2);
if (args[0] === 'test') {
  await test();
} else if (args[0] === '--out' && args.length === 2) {
  await build(resolve(args[1]));
} else if (args.length === 0) {
  await build(DIST);
} else {
  console.error('usage: node build.mjs [--out DIR | test]');
  process.exit(2);
}
