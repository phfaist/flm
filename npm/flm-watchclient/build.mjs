// The build of flm-watchclient, the member `flm-watchclient` of the workspace npm/.
//
//   node build.mjs              type check, then write the built files into the folder of
//                               the crate flm-host that embeds them (OUT)
//   node build.mjs --out DIR    the same, written into DIR instead of OUT
//   node build.mjs test         compile test/*.test.ts into target/test/ and run them
//                               with node's test runner
//
// The built files (OUTPUTS):
//
// - `flm-watchclient.js`, the page script: esbuild's bundle of src/page/index.ts as one
//   IIFE that assigns no global name, with the library `morphdom`;
// - `flm-watchclient.css`, its stylesheet: src/page/page.css;
// - `tools/index.html`, the tools page: src/tools/index.html;
// - `tools/tools.js`, its script: esbuild's bundle of src/tools/main.tsx, with Preact, its
//   signals, the core of highlight.js with its LaTeX grammar, ansi_up, and the icons it
//   imports from the package `lucide-static` (ICONS);
// - `tools/tools.css`, its stylesheet: src/tools/tools.css, whose rules of the PDF view's
//   text layer are adapted from the stylesheet of `pdfjs-dist` (TEXT_LAYER);
// - `tools/pdfjs/`, the files of the library `pdfjs-dist` that the PDF view loads when it
//   shows a PDF (PDFJS): the library and its worker, each under the header of a script
//   that holds the library, then as the package ships it; and the two fonts of the
//   package that a PDF can use without holding them (Symbol and ZapfDingbats), as the
//   package ships them, with their licenses in `standard_fonts/LICENSES.txt`.
//
// Nothing that esbuild bundles is minified; the scripts of pdf.js are copied as the package
// ships them, minified. Each text file begins with the line GENERATED: in a comment in the
// scripts, the stylesheets and the pages, as plain text in the fonts' licenses
// (`LICENSES.txt`); the fonts are copied as they are. Each script then
// holds the licenses of the libraries it holds, which esbuild's account of its inputs gives
// for a bundle, each with its version; the tools page's stylesheet holds the license of
// pdf.js in the same way. Neither the page script nor its stylesheet may
// hold the text that would end the element (`</script`, `</style`) that the page writes
// it into. The type checker and esbuild are the workspace's (`npm install` in npm/);
// esbuild works from this script's folder, so the outputs are the same from whichever
// folder the script is run.

import { spawnSync, execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from 'node:fs';
import { basename, dirname, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const here = dirname(fileURLToPath(import.meta.url));

/** The workspace's installed packages. */
const MODULES = join(here, '..', 'node_modules');

/** The folder of the crate flm-host that holds the files it embeds. */
const OUT = join(here, '..', '..', 'flm-host', 'src', 'watch', 'client');

/** The first line of each built file, without the comment's delimiters. */
const GENERATED = 'Generated by npm/flm-watchclient (node build.mjs); do not edit.';

/** The browsers the scripts are written for: the current evergreen ones. */
const TARGET = ['es2022'];

/**
 * The icons: a script imports an icon as the text of its SVG file in the package
 * `lucide-static` (`import check from 'lucide-static/icons/check.svg'`). The text is
 * bundled without the file's comment and the blank space between its elements; the
 * package's license goes into the script's header as any library's does.
 */
const ICONS = {
  name: 'lucide-icons',
  setup(build) {
    build.onLoad({ filter: /[\\/]lucide-static[\\/]icons[\\/][a-z0-9-]+\.svg$/ }, (args) => ({
      contents: read(args.path).replace(/<!--[\s\S]*?-->/g, '').replace(/>\s+</g, '><').replace(/\s+/g, ' ').trim(),
      loader: 'text',
    }));
  },
};

/**
 * The files of `pdfjs-dist` that the tools page serves, by their path in the package: the
 * library and its worker (each as one module), and the fonts that the library fetches for
 * a font a PDF names without holding it. Of the standard fonts, the browser's own are used
 * (the library's default), except for Symbol and ZapfDingbats, which the library always
 * draws from its own files. The text layer is drawn by the library itself.
 */
const PDFJS = {
  scripts: ['build/pdf.min.mjs', 'build/pdf.worker.min.mjs'],
  fonts: ['standard_fonts/FoxitDingbats.pfb', 'standard_fonts/FoxitSymbol.pfb'],
  fontLicenses: ['standard_fonts/LICENSE_FOXIT'],
};

/**
 * The library whose stylesheet (`web/pdf_viewer.css`) the rules of the text layer in
 * src/tools/tools.css are adapted from.
 */
const TEXT_LAYER = 'pdfjs-dist';

/** The names a library's license file may have, in the order they are looked for. */
const LICENSE_FILES = ['LICENSE', 'LICENSE.md', 'LICENSE.txt'];

function read(path) {
  return readFileSync(path, 'utf8');
}

function typeCheck() {
  const tsc = join(MODULES, '.bin', 'tsc');
  execFileSync(tsc, ['--noEmit', '-p', join(here, 'tsconfig.json')], { stdio: 'inherit' });
}

/** `text` as line comments. */
function commented(text) {
  return text.trimEnd().split('\n').map((line) => (line === '' ? '//' : `// ${line}`)).join('\n') + '\n';
}

/**
 * The libraries bundled into a script, given esbuild's account of its inputs: each
 * package of the workspace's `node_modules` an input lies in, sorted by name, with its
 * version and the text of its license.
 */
function librariesOf(metafile) {
  const prefix = MODULES + sep;
  const names = new Set();
  for (const input of Object.keys(metafile.inputs)) {
    const path = resolve(here, input);
    if (!path.startsWith(prefix)) continue;
    const parts = path.slice(prefix.length).split(sep);
    names.add(parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0]);
  }
  return [...names].sort().map(library);
}

/** The library `name` of the workspace's `node_modules`: its version, license and the text of its license. */
function library(name) {
  const folder = join(MODULES, ...name.split('/'));
  const { version, license } = JSON.parse(read(join(folder, 'package.json')));
  const file = LICENSE_FILES.find((candidate) => existsSync(join(folder, candidate)));
  if (file === undefined) throw new Error(`Missing license file of the library ‘${name}’ (looked for ${LICENSE_FILES.join(', ')})`);
  return { name, version, license, text: read(join(folder, file)) };
}

/**
 * The text of a built file's header: GENERATED, then, when `libraries` is not empty, the
 * sentence `holds` (completed by the libraries' names) and the license of each library.
 */
function headerText(holds, libraries) {
  const lines = [GENERATED];
  if (libraries.length > 0) {
    const names = libraries.map(({ name, version }) => `${name} ${version}`).join(', ');
    const which = libraries.length === 1 ? `the library ${names}; its license follows` : `the libraries ${names}; their licenses follow`;
    lines.push('', `${holds} ${which}.`);
    for (const { name, version, license, text } of libraries) {
      lines.push('', `${name} ${version} (license ${license}):`, '', text.trimEnd());
    }
  }
  return lines.join('\n');
}

/** A script's header: GENERATED, then the license of each library it holds. */
function scriptHeader(libraries) {
  return commented(headerText('This script holds', libraries)) + '\n';
}

/**
 * A stylesheet's header: GENERATED, then the license of each library whose rules it adapts
 * (`adapted`), in one comment.
 */
function styleHeader(adapted) {
  const text = headerText('This stylesheet holds rules adapted from those of', adapted);
  if (text.includes('*/')) throw new Error('A license holds the end of a CSS comment (‘*/’)');
  const [first, ...rest] = text.split('\n');
  if (rest.length === 0) return `/* ${first} */\n`;
  return [`/* ${first}`, ...rest.map((line) => (line === '' ? ' *' : ` * ${line}`)), ' */', '', ''].join('\n');
}

/** Bundles the script `entry` (a path in this package) as one IIFE: its text, header included. */
async function bundle(entry) {
  const result = await esbuild.build({
    absWorkingDir: here,
    entryPoints: [join(here, entry)],
    bundle: true,
    write: false,
    outdir: join(here, 'target', 'staging'),
    format: 'iife',
    target: TARGET,
    minify: false,
    metafile: true,
    jsx: 'automatic',
    jsxImportSource: 'preact',
    plugins: [ICONS],
    // The PDF view loads pdf.js from the server when it shows a PDF.
    external: ['/.flm-preview/*'],
    legalComments: 'none',
    charset: 'utf8',
    logLevel: 'warning',
  });
  const [output] = result.outputFiles.filter((file) => file.path.endsWith('.js'));
  return scriptHeader(librariesOf(result.metafile)) + output.text;
}

/**
 * The stylesheet `path` (a path in this package), under GENERATED and the licenses of the
 * libraries whose rules it adapts (`adapted`, names of the workspace's packages).
 */
function style(path, adapted = []) {
  return styleHeader(adapted.map(library)) + read(join(here, path));
}

/** The page `path` (a path in this package), GENERATED after its first line, the doctype. */
function page(path) {
  const [doctype, ...rest] = read(join(here, path)).split('\n');
  if (doctype !== '<!DOCTYPE html>') throw new Error(`Missing doctype on the first line of ‘${path}’`);
  return [doctype, `<!-- ${GENERATED} -->`, ...rest].join('\n');
}

/**
 * The files of `pdfjs-dist` (PDFJS), by their path under `tools/pdfjs/`: each script under
 * the header of a script that holds the library, the fonts' bytes as the package ships
 * them, and the fonts' licenses in one text file.
 */
function pdfjs() {
  const holds = library('pdfjs-dist');
  const folder = join(MODULES, 'pdfjs-dist');
  const files = {};
  for (const path of PDFJS.scripts) files[basename(path)] = scriptHeader([holds]) + read(join(folder, path));
  for (const path of PDFJS.fonts) files[`standard_fonts/${basename(path)}`] = readFileSync(join(folder, path));
  const licenses = PDFJS.fontLicenses.map((path) => `${holds.name} ${holds.version}, ${path}:\n\n${read(join(folder, path)).trimEnd()}\n`);
  const fonts = PDFJS.fonts.map((path) => basename(path)).join(', ');
  files['standard_fonts/LICENSES.txt'] = `${GENERATED}\n\nThe licenses of the fonts ${fonts}, files of the library ${holds.name} ${holds.version}:\n\n${licenses.join('\n')}`;
  return files;
}

/** Fails when the page script or its stylesheet holds the text that ends its element. */
function checkInline(files) {
  const problems = [];
  for (const [name, closing] of [['flm-watchclient.js', '</script'], ['flm-watchclient.css', '</style']]) {
    if (files[name].toLowerCase().includes(closing)) problems.push(`‘${closing}’ may not appear in ‘${name}’ (the page writes it inline)`);
  }
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem);
    process.exit(1);
  }
}

async function build(outDir) {
  typeCheck();
  const files = {
    'flm-watchclient.js': await bundle('src/page/index.ts'),
    'flm-watchclient.css': style('src/page/page.css'),
    'tools/index.html': page('src/tools/index.html'),
    'tools/tools.js': await bundle('src/tools/main.tsx'),
    'tools/tools.css': style('src/tools/tools.css', [TEXT_LAYER]),
  };
  for (const [name, contents] of Object.entries(pdfjs())) files[`tools/pdfjs/${name}`] = contents;
  checkInline(files);
  rmSync(join(outDir, 'tools'), { recursive: true, force: true });
  for (const [name, contents] of Object.entries(files)) {
    mkdirSync(dirname(join(outDir, name)), { recursive: true });
    writeFileSync(join(outDir, name), contents);
  }
}

async function test() {
  const outDir = join(here, 'target', 'test');
  rmSync(outDir, { recursive: true, force: true });
  const files = readdirSync(join(here, 'test')).filter((name) => name.endsWith('.test.ts')).sort();
  await esbuild.build({
    absWorkingDir: here,
    entryPoints: files.map((name) => join(here, 'test', name)),
    outdir: outDir,
    outExtension: { '.js': '.mjs' },
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node22',
    external: ['node:*'],
    jsx: 'automatic',
    jsxImportSource: 'preact',
    plugins: [ICONS],
    logLevel: 'warning',
  });
  const compiled = files.map((name) => join(outDir, name.replace(/\.ts$/, '.mjs')));
  const run = spawnSync(process.execPath, ['--test', ...compiled], { stdio: 'inherit' });
  process.exit(run.status ?? 1);
}

const args = process.argv.slice(2);
if (args[0] === 'test') {
  await test();
} else if (args[0] === '--out' && args.length === 2) {
  await build(resolve(args[1]));
} else if (args.length === 0) {
  await build(OUT);
} else {
  console.error('usage: node build.mjs [--out DIR | test]');
  process.exit(2);
}
