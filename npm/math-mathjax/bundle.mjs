// Builds `extensions/js/math-mathjax/vendor/mathjax.js` (the MathJax bundle, one
// minified ES module exporting the object `MathJax` of `entry.mjs`) and
// `extensions/js/math-mathjax/vendor/bundle.js` (the packages bundled and the
// MathJax version), under node, from the workspace `npm/`:
//
//   npm install                    (once, in npm/)
//   npm run build -w math-mathjax  (in npm/; or `node bundle.mjs` in this folder)
//
// The esbuild call is the experiment's (branch `experiment-quickjs`,
// `prototypes/experiment-quickjs/js/build.mjs`), with an ES module as the
// output instead of a classic script and one entry instead of three.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MathJax } from './entry.mjs';

const here = dirname(fileURLToPath(import.meta.url));
/** The extension's folder of generated files. */
const vendor = join(here, '..', '..', 'extensions', 'js', 'math-mathjax', 'vendor');

const VERSION = JSON.parse(readFileSync(join(here, '..', 'node_modules', '@mathjax', 'src', 'package.json'), 'utf8')).version;
const HEADER = `// Generated by npm/math-mathjax/bundle.mjs from MathJax ${VERSION} (@mathjax/src); do not edit.\n`
  + '// MathJax: Copyright (c) The MathJax Consortium, licensed under the Apache License, Version 2.0.\n';

const outfile = join(vendor, 'mathjax.js');
const result = await build({
  absWorkingDir: here, entryPoints: ['entry.mjs'], bundle: true, format: 'esm',
  platform: 'neutral', target: 'es2020', minify: true, write: false, logLevel: 'warning',
  mainFields: ['module', 'main'], legalComments: 'none',
});
writeFileSync(outfile, HEADER + result.outputFiles[0].text);
writeFileSync(join(vendor, 'bundle.js'), HEADER
  + '// The MathJax TeX packages the bundle holds, and the MathJax version.\n'
  + `export const PACKAGES = Object.freeze(${JSON.stringify(MathJax.PACKAGES)});\n`
  + `export const VERSION = ${JSON.stringify(VERSION)};\n`);
console.log(outfile, (statSync(outfile).size / 1024).toFixed(0), 'KiB');
